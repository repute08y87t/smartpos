PRAGMA foreign_keys = ON;
CREATE TABLE IF NOT EXISTS products (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT NOT NULL,
    price REAL NOT NULL,
    stock REAL DEFAULT 0,
    sku TEXT UNIQUE,
    category TEXT DEFAULT 'General',
    subcategory TEXT DEFAULT '',
    brand TEXT DEFAULT '',
    size TEXT DEFAULT '',
    cost_price REAL DEFAULT 0,
    pack_size INTEGER DEFAULT 1,
    pack_cost REAL DEFAULT 0,
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS sales (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    receipt_no TEXT UNIQUE NOT NULL,
    subtotal REAL NOT NULL,
    discount_amount REAL DEFAULT 0,
    tax_amount REAL DEFAULT 0,
    total REAL NOT NULL,
    status TEXT DEFAULT 'completed',
    timestamp DATETIME DEFAULT CURRENT_TIMESTAMP,
    payment_timestamp DATETIME,
    method TEXT DEFAULT 'cash',
    phone TEXT,
    receipt_code TEXT,
    parent_receipt TEXT
);
CREATE TABLE IF NOT EXISTS sale_items (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    sale_id INTEGER NOT NULL,
    product_id INTEGER NOT NULL,
    qty REAL NOT NULL,
    unit_price REAL NOT NULL,
    total_price REAL NOT NULL,
    cost_price REAL DEFAULT 0,
    FOREIGN KEY (sale_id) REFERENCES sales(id) ON DELETE CASCADE,
    FOREIGN KEY (product_id) REFERENCES products(id)
);
CREATE TABLE IF NOT EXISTS users (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    username TEXT UNIQUE NOT NULL,
    password TEXT NOT NULL,
    role TEXT NOT NULL CHECK(role IN ('owner', 'cashier')),
    pin TEXT,
    full_name TEXT NOT NULL,
    is_active INTEGER DEFAULT 1,
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS shifts (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id INTEGER NOT NULL,
    opened_at DATETIME NOT NULL,
    closed_at DATETIME,
    opening_cash REAL DEFAULT 0,
    opening_mpesa REAL DEFAULT 0,
    cash_sales REAL DEFAULT 0,
    mpesa_sales REAL DEFAULT 0,
    cash_out REAL DEFAULT 0,
    total_cash_in REAL DEFAULT 0,
    total_cash_out REAL DEFAULT 0,
    expected_cash REAL DEFAULT 0,
    expected_mpesa REAL DEFAULT 0,
    actual_cash REAL,
    actual_mpesa REAL,
    cash_variance REAL,
    mpesa_variance REAL,
    notes TEXT,
    is_active INTEGER DEFAULT 1
);
CREATE TABLE IF NOT EXISTS mpesa_transactions (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    amount REAL NOT NULL,
    phone TEXT NOT NULL,
    receipt_code TEXT NOT NULL UNIQUE,
    transaction_time DATETIME NOT NULL,
    claimed INTEGER DEFAULT 0,
    claimed_sale_id INTEGER,
    claimed_at DATETIME,
    raw_sms_text TEXT
);
CREATE TABLE IF NOT EXISTS refunds (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    sale_id INTEGER,
    amount REAL NOT NULL,
    reason TEXT,
    timestamp DATETIME DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL,
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS categories (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT UNIQUE NOT NULL,
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS subcategories (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    category_id INTEGER,
    name TEXT NOT NULL,
    FOREIGN KEY(category_id) REFERENCES categories(id),
    UNIQUE(category_id, name)
);
CREATE TABLE IF NOT EXISTS brands (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    category_id INTEGER,
    subcategory_id INTEGER,
    name TEXT NOT NULL,
    FOREIGN KEY(category_id) REFERENCES categories(id),
    UNIQUE(category_id, subcategory_id, name)
);
